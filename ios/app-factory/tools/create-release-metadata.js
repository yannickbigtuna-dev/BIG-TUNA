#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const { readJson, validateSpec, sha256, mkdirp, writeJson } = require('./factory-lib');
function arg(name) { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : null; }
const specFile = arg('--spec'), ipa = arg('--ipa'), output = arg('--output'), notes = arg('--notes');
if (!specFile || !ipa || !output) { console.error('Usage: node create-release-metadata.js --spec <spec.yml> --ipa <file.ipa> --output <release-directory> [--notes <release-notes.txt>]'); process.exit(2); }
try {
  const spec = validateSpec(readJson(specFile), specFile);
  if (!fs.statSync(ipa).isFile()) throw new Error(`IPA was not found: ${ipa}`);
  mkdirp(output);
  const ipaName = `${spec.app.slug}-${spec.app.version}-${spec.app.build}.ipa`;
  const destination = path.join(output, ipaName);
  fs.copyFileSync(ipa, destination);
  const digest = sha256(destination);
  const releaseDate = new Date().toISOString();
  const metadata = {
    schemaVersion: 1, app: spec.app, factory: spec.factory, targets: spec.targets, capabilities: spec.capabilities,
    releaseDate, ipa: ipaName, sha256: digest,
    installation: { signing: 'local-free-account-required', expiresAfterDays: 7, directSafariInstall: false },
    sourceSpec: path.basename(specFile)
  };
  writeJson(path.join(output, 'manifest.json'), metadata);
  fs.writeFileSync(path.join(output, 'sha256.txt'), `${digest}  ${ipaName}\n`, 'utf8');
  const releaseNotes = notes ? fs.readFileSync(notes, 'utf8') : `# ${spec.app.name} ${spec.app.version} (${spec.app.build})\n\n- Build generated by Apple App Factory.\n- Requires local signing with the owner's Apple Account; free Personal Team signatures expire after seven days.\n`;
  fs.writeFileSync(path.join(output, 'release-notes.txt'), releaseNotes, 'utf8');
  console.log(JSON.stringify({ ok: true, output: path.resolve(output), ipa: ipaName, sha256: digest }, null, 2));
} catch (error) { console.error(`Release metadata generation failed: ${error.message}`); process.exit(1); }
